CURRENT_LANG = "nl"


def set_language(lang: str) -> None:
    """Stel de actieve taal in ('nl' of 'en')."""
    global CURRENT_LANG
    if lang in TRANSLATIONS:
        CURRENT_LANG = lang


def tr(key: str) -> str:
    """Vertaal een UI-tekst naar de actieve taal (fallback: de sleutel)."""
    if not isinstance(key, str):
        return key
    lang_dict = TRANSLATIONS.get(CURRENT_LANG, {})
    return lang_dict.get(key, key)


