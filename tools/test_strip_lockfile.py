"""
Tests for strip-private-registry-lockfile.py
Run with: pytest tools/test_strip_lockfile.py
"""

import importlib.util
import sys
from pathlib import Path

# The script filename uses hyphens, so it can't be imported with a normal
# import statement. Load it explicitly by file path instead.
_script = Path(__file__).parent / "strip-private-registry-lockfile.py"
_spec = importlib.util.spec_from_file_location(
    "strip_private_registry_lockfile", _script
)
_mod = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_mod)

filter_lockfile = _mod.filter_lockfile
parse_blocks = _mod.parse_blocks

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

# Yarn Berry lockfiles open with comment lines — those become the empty-header preamble block.
PREAMBLE = "__metadata:\n  version: 6\n  cacheKey: 8c0\n\n"

# A leading comment block that parse_blocks recognises as the preamble (header='').
COMMENT_PREAMBLE = (
    "# This file is generated by running 'yarn install' inside your project.\n"
    "# Manual changes might be lost - proceed with caution!\n"
    "\n"
)

PUBLIC_BLOCK = (
    '"lodash@npm:^4.17.21":\n'
    "  version: 4.17.21\n"
    '  resolution: "lodash@npm:4.17.21"\n'
    "  checksum: abc123\n"
    "\n"
)

PRIVATE_ARCHIVE_BLOCK = (
    '"@tpe/quark-client@npm:1.2.1":\n'
    "  version: 1.2.1\n"
    '  resolution: "@tpe/quark-client@npm:1.2.1::__archiveUrl=https%3A%2F%2Fprivate.registry.example.com%2F%40tpe%2Fquark-client%2F-%2Fquark-client-1.2.1.tgz"\n'
    "  checksum: def456\n"
    "\n"
)

PRIVATE_SCOPE_BLOCK = (
    '"@acme/utils@npm:2.0.0":\n'
    "  version: 2.0.0\n"
    '  resolution: "@acme/utils@npm:2.0.0"\n'
    "  checksum: ghi789\n"
    "\n"
)


# ---------------------------------------------------------------------------
# parse_blocks
# ---------------------------------------------------------------------------


class TestParseBlocks:
    def test_preamble_is_block_with_empty_header(self):
        text = COMMENT_PREAMBLE + PUBLIC_BLOCK
        blocks = parse_blocks(text)
        assert blocks[0][2] == "", "first block should be the preamble (header='')"

    def test_public_block_has_correct_header(self):
        text = PREAMBLE + PUBLIC_BLOCK
        blocks = parse_blocks(text)
        headers = [h for _, _, h in blocks if h]
        assert '"lodash@npm:^4.17.21"' in headers

    def test_stray_blank_lines_are_preserved(self):
        # Two consecutive blank lines between blocks — the second is "stray".
        text = PREAMBLE + PUBLIC_BLOCK + "\n" + PUBLIC_BLOCK
        blocks = parse_blocks(text)
        # Reconstruct and verify the stray blank line is present.
        lines = text.splitlines(keepends=True)
        reconstructed = "".join("".join(lines[s:e]) for s, e, _ in blocks)
        assert reconstructed == text

    def test_trailing_blank_lines_are_preserved(self):
        text = PREAMBLE + PUBLIC_BLOCK + "\n\n"
        blocks = parse_blocks(text)
        lines = text.splitlines(keepends=True)
        reconstructed = "".join("".join(lines[s:e]) for s, e, _ in blocks)
        assert reconstructed == text


# ---------------------------------------------------------------------------
# filter_lockfile — removal logic
# ---------------------------------------------------------------------------


class TestFilterLockfile:
    def test_public_package_is_kept(self):
        src = PREAMBLE + PUBLIC_BLOCK
        filtered, removed = filter_lockfile(src, private_scopes=set())
        assert "lodash" in filtered
        assert removed == []

    def test_private_archive_url_is_removed(self):
        src = PREAMBLE + PUBLIC_BLOCK + PRIVATE_ARCHIVE_BLOCK
        filtered, removed = filter_lockfile(src, private_scopes=set())
        assert "lodash" in filtered
        assert "@tpe/quark-client" not in filtered
        assert len(removed) == 1
        assert "@tpe/quark-client" in removed[0]

    def test_private_scope_is_removed_when_declared(self):
        src = PREAMBLE + PUBLIC_BLOCK + PRIVATE_SCOPE_BLOCK
        filtered, removed = filter_lockfile(src, private_scopes={"@acme"})
        assert "lodash" in filtered
        assert "@acme/utils" not in filtered
        assert len(removed) == 1

    def test_private_scope_is_kept_when_not_declared(self):
        # Without declaring @acme as private, the block has no archiveUrl so it
        # passes through untouched.
        src = PREAMBLE + PUBLIC_BLOCK + PRIVATE_SCOPE_BLOCK
        filtered, removed = filter_lockfile(src, private_scopes=set())
        assert "@acme/utils" in filtered
        assert removed == []

    def test_preamble_always_kept(self):
        src = PREAMBLE + PRIVATE_ARCHIVE_BLOCK
        filtered, removed = filter_lockfile(src, private_scopes=set())
        assert "__metadata" in filtered

    def test_output_is_valid_when_all_private_removed(self):
        src = PREAMBLE + PRIVATE_ARCHIVE_BLOCK
        filtered, removed = filter_lockfile(src, private_scopes=set())
        assert len(removed) == 1
        # The output should still contain the preamble and end cleanly.
        assert filtered.strip() != ""

    def test_stray_blank_lines_survive_filtering(self):
        # A stray extra blank line between blocks must be present in the output.
        src = PREAMBLE + PUBLIC_BLOCK + "\n" + PUBLIC_BLOCK
        filtered, removed = filter_lockfile(src, private_scopes=set())
        assert filtered == src

    def test_dry_run_does_not_affect_output(self):
        src = PREAMBLE + PUBLIC_BLOCK + PRIVATE_ARCHIVE_BLOCK
        filtered_normal, _ = filter_lockfile(src, private_scopes=set(), dry_run=False)
        filtered_dry, _ = filter_lockfile(src, private_scopes=set(), dry_run=True)
        # dry_run only suppresses file writing at the CLI level; the returned
        # text should be identical.
        assert filtered_normal == filtered_dry
